def build():
    shutil.copy2(TEMPLATE, OUTPUT)
    doc = Document(OUTPUT)

    replacements = {
        4: "Кафедра спортивной медицины и комплексной реабилитации",
        5: "Дисциплина «Спортивный массаж»",
        7: "Риваненкова Надежда Сергеевна",
        8: "«Спортивный массаж»",
        19: "2026",
    }
    for idx, text in replacements.items():
        p = doc.paragraphs[idx]
        p.text = text
        for run in p.runs:
            set_run_font(run)

    clear_body(doc, 20)

    add_heading(doc, "СОДЕРЖАНИЕ")
    doc.add_paragraph()
    toc = [
        ("ВВЕДЕНИЕ", "3"),
        ("ОСНОВНЫЕ ПРИНЦИПЫ МАССАЖА", "5"),
        ("МЕТОДИКА МАССАЖА И ОСНОВНЫЕ ПРИЁМЫ", "8"),
        ("СПОРТИВНЫЙ МАССАЖ", "12"),
        ("ЗАКЛЮЧЕНИЕ", "20"),
        ("ИСТОЧНИКИ", "21"),
    ]
    for title, page in toc:
        add_toc_line(doc, title, page)

    doc.add_page_break()

    add_heading(doc, "ВВЕДЕНИЕ")
    for para in INTRO:
        add_paragraph(doc, para)

    doc.add_page_break()

    add_heading(doc, "ОСНОВНЫЕ ПРИНЦИПЫ МАССАЖА")
    for para in PRINCIPLES:
        add_paragraph(doc, para)

    doc.add_page_break()

    add_heading(doc, "МЕТОДИКА МАССАЖА И ОСНОВНЫЕ ПРИЁМЫ")
    for para in METHODIKA:
        add_paragraph(doc, para)

    doc.add_page_break()

    add_heading(doc, "СПОРТИВНЫЙ МАССАЖ")
    for para in SPORT:
        add_paragraph(doc, para)

    doc.add_page_break()

    add_heading(doc, "ЗАКЛЮЧЕНИЕ")
    for para in CONCLUSION:
        add_paragraph(doc, para)

    doc.add_page_break()

    add_heading(doc, "ИСТОЧНИКИ:")
    for src in SOURCES:
        add_paragraph(doc, src, indent=False)

    doc.save(OUTPUT)
    print(f"Saved: {OUTPUT}")


if __name__ == "__main__":
    build()
