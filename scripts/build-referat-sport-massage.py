FIRST_LINE = Cm(1.25)


def delete_paragraph(paragraph):
    element = paragraph._element
    element.getparent().remove(element)


def set_run_font(run):
    run.font.name = FONT_NAME
    run.font.size = FONT_SIZE
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT_NAME)


def add_paragraph(doc, text, *, align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=True, bold=False):
    p = doc.add_paragraph()
    p.alignment = align
    fmt = p.paragraph_format
    fmt.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    fmt.space_before = Pt(0)
    fmt.space_after = Pt(0)
    if indent and align == WD_ALIGN_PARAGRAPH.JUSTIFY:
        fmt.first_line_indent = FIRST_LINE
    else:
        fmt.first_line_indent = None
    run = p.add_run(text)
    set_run_font(run)
    run.bold = bold
    return p


def add_heading(doc, text):
    return add_paragraph(doc, text, align=WD_ALIGN_PARAGRAPH.CENTER, indent=False, bold=False)


def add_toc_line(doc, title, page):
    dots = "…" * max(3, 42 - len(title) // 2)
    add_paragraph(doc, f"{title}{dots}{page}", align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=False)


def clear_body(doc, start_index):
    while len(doc.paragraphs) > start_index:
        delete_paragraph(doc.paragraphs[start_index])


